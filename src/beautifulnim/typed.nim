## `beautifulnim check --typed`: the rules of `analyze.nim`, with BN-02 decided on the types the
## compiler resolves instead of the names written (docs/specification.md BN-T, ADR-BNIM-0003).
##
## The file is checked the way `nim check` checks it: the nim.cfg and config.nims files that
## `nim check` would read apply, and imports are resolved. The standard library used is the one of
## the Nim that built this checker, because the compiler modules compiled into it must match it.
## Importing this module compiles Nim's semantic checker into the program; `import beautifulnim`
## alone does not.

when not defined(nimcore):
  {.error: "beautifulnim/typed needs -d:nimcore: without it the compiler's VM does not register " &
    "compile-time procs such as querySetting, and checking code that calls them fails".}

import std/[algorithm, compilesettings, os, strutils]
import compiler/[ast, astalgo, cmdlinehelper, commands, condsyms, idents, lineinfos, modulegraphs,
                 msgs, options, pathutils, pipelines]
import ./[analyze, rules]

type
  CompileError* = object
    file*: string ## the checked file as given, or the full path of an imported file; "" when unknown
    line*, col*: int ## 1-based; 0 when the compiler gave no place
    message*: string

  TypedAnalysis* = object
    ok*: bool ## false when the file cannot be read, does not parse or does not compile; findings are then empty
    readError*: string ## why the file could not be read; "" when it was read
    findings*: seq[Finding] ## ordered by line, then column
    errors*: seq[CompileError]

  NamingVerdict = enum
    ## What the symbol says about a BN-05 finding at it (BN-T7).
    nvKeep ## as the syntax rule decided
    nvDrop ## wrong: a foreign name, or a getFoo whose parameter has no fields
    nvWarn ## a getFoo that reads a field of its parameter: level warning

  ErrorSink = ref object
    errors: seq[CompileError]

const
  Routines = {skProc, skFunc, skMethod, skIterator, skTemplate, skMacro, skConverter}
  ## What a parameter's type is written through without changing what it is.
  Transparent = {tyVar, tySink, tyAlias, tyGenericInst}

let builtWithStdlib* = querySetting(libPath)
  ## The standard library of the Nim that built this program; the compiler modules compiled into
  ## it match that library and no other.

proc errorFile(conf: ConfigRef; info: TLineInfo; path: string): string =
  if info.fileIndex == InvalidFileIdx: ""
  elif info.fileIndex == conf.projectMainIdx: path
  else: toFullPath(conf, info)

proc userHook(g: ModuleGraph; t: PType; op: TTypeAttachedOp): bool =
  ## Whether the hook `op` of `t` was written by the user (`{.error.}` included) rather than
  ## generated by the compiler from the fields.
  let h = getAttachedOp(g, t, op)
  h != nil and sfOverridden in h.flags

proc destroysWithoutCopy(g: ModuleGraph; t: PType): bool =
  ## BN-T6: `t` has its own `=destroy` but no `=copy` of its own, so an assignment copies the
  ## fields and both values release the same resource. A `=dup` alone does not count: assigning
  ## to an existing variable still calls `=copy`. A generic type's hooks are bound to its body.
  let body = if t.kind == tyGenericBody: t.last else: t
  for x in [t, body]:
    if userHook(g, x, attachedDestructor):
      return not userHook(g, x, attachedAsgn)
  false

proc isGetterOfValue(s: PSym): bool =
  ## BN-T7: the single parameter of the `getFoo` routine `s` is a value with fields (an object or
  ## a tuple, also through `var`, `sink`, `ptr`, `ref` and aliases), so `getFoo` reads a field
  ## or a property of it. A string key, a number or a generic parameter is not such a value.
  let params = s.typ.n
  if params.isNil or params.len != 2 or params[1].kind != nkSym or params[1].sym.typ.isNil:
    return false
  params[1].sym.typ.skipTypes(Transparent + {tyPtr, tyRef}).kind in {tyObject, tyTuple}

proc hasField(t: PType; field: PIdent): bool =
  ## Whether the object or tuple `t` (through `var`, `sink`, `ptr`, `ref` and aliases) has a field
  ## named `field`, also one inherited from a base object. Names compare as Nim compares them.
  var t = t.skipTypes(Transparent + {tyPtr, tyRef})
  while t != nil:
    case t.kind
    of tyObject:
      if t.n != nil and lookupInRecord(t.n, field) != nil: return true
      let base = t.baseClass
      t = if base.isNil: nil else: base.skipTypes(Transparent + {tyPtr, tyRef})
    of tyTuple:
      return t.n != nil and lookupInRecord(t.n, field) != nil
    else:
      return false
  false

proc namingVerdict(s: PSym; cache: IdentCache): NamingVerdict =
  ## BN-T7: what the symbol says about a BN-05 finding at `s`. A foreign name stays, however the
  ## pragma got there (`{.push importc.}`, a `{.pragma: x, importc.}` alias); the syntax rule sees
  ## only pragmas written on the declaration itself. A `getFoo` that reads the field `foo` of its
  ## parameter has no reason for the prefix (the guide allows it only for expensive calls); one
  ## that computes its value keeps the syntax rule's level.
  if s.flags * {sfImportc, sfExportc} != {}: return nvDrop
  let n = s.name.s
  if s.kind notin Routines or n.len <= 3 or not n.startsWith("get") or n[3] notin {'A'..'Z'}:
    return nvKeep
  if not isGetterOfValue(s): return nvDrop
  let field = cache.getIdent(toLowerAscii(n[3]) & n[4 .. ^1])
  if hasField(s.typ.n[1].sym.typ, field): nvWarn else: nvKeep

proc freedOnReturn(owner: PSym; n: PNode): bool =
  ## BN-T8: the string `n` does not outlive the routine `owner`: a temporary (the result of a call
  ## or an operator), a local variable of `owner`, or a `sink` parameter, which `owner` owns. A
  ## plain parameter and its fields belong to the caller; globals and literals stay.
  case n.kind
  of nkCall, nkInfix, nkPrefix, nkPostfix, nkCommand, nkCallStrLit, nkStmtListExpr:
    true
  of nkSym:
    let v = n.sym
    (v.kind in {skVar, skLet} and v.owner == owner and sfGlobal notin v.flags) or
      (v.kind == skParam and v.typ != nil and v.typ.kind == tySink)
  else:
    false

proc danglingCstrings(owner: PSym; n: PNode; found: var seq[Finding]) =
  ## BN-T8: each assignment to `result` (also the one a `return x` or a last expression becomes)
  ## of a `cstring` converted from a string that is freed when `owner` returns.
  if n.isNil: return
  if n.kind == nkAsgn and n.len == 2 and n[0].kind == nkSym and n[0].sym.kind == skResult:
    # A routine with a `##` comment wraps its last expression with the comment (nkStmtListExpr).
    var rhs = n[1]
    while rhs.kind in {nkStmtListExpr, nkStmtList} and rhs.len > 0: rhs = rhs[^1]
    if rhs.kind in {nkConv, nkHiddenStdConv} and rhs.typ != nil and rhs.typ.kind == tyCstring:
      let src = rhs[^1]
      if src.typ != nil and src.typ.skipTypes(Transparent).kind == tyString and
          freedOnReturn(owner, src):
        found.add initFinding(bn12DanglingCstring, int(rhs.info.line), int(rhs.info.col) + 1)
  if n.kind notin {nkSym, nkIdent, nkEmpty, nkNilLit, nkType} + nkLiterals:
    for c in n: danglingCstrings(owner, c, found)

proc semCheck(path, stdlib: string; sink: ErrorSink;
              naming: var seq[(int, int, NamingVerdict)]): seq[Finding] =
  ## Runs the compiler's semantic pass on `path` as the main module and returns a BN-02 finding
  ## for each parameter of type bool of each public routine declared in it (BN-T1), and a BN-11
  ## finding for each type declared in it that has its own `=destroy` but no `=copy` (BN-T6).
  ## `naming` receives the place and verdict of each routine and type whose BN-05 finding the
  ## symbol changes (BN-T7).
  let cache = newIdentCache()
  let conf = newConfigRef()
  let prog = NimProg(suggestMode: true,
    processCmdLine: proc (pass: TCmdLinePass; cmd: string; conf: ConfigRef) =
      if pass == passCmd1: conf.projectName = path)
  prog.initDefinesProg(conf, "beautifulnim")
  prog.processCmdLineAndProjectPath(conf)
  conf.prefixDir = AbsoluteDir(stdlib.parentDir)
  # Errors arrive through the hook below. What else the compiler prints (hints, output of
  # `static: echo`) is not part of the result.
  conf.writelnHook = proc (msg: string) = discard
  conf.errorMax = high(int) # collect every error, not only the first
  conf.structuredErrorHook = proc (config: ConfigRef; info: TLineInfo; msg: string;
                                   level: Severity) {.closure, gcsafe.} =
    # Inside compiles() and similar trials errorOutputs is {}: those errors are expected.
    if level == Severity.Error and config.m.errorOutputs != {}:
      let e = CompileError(file: errorFile(config, info, path), line: int(info.line),
        col: (if info.line == 0: 0 else: int(info.col) + 1), message: msg)
      # the compiler reports some errors twice at the same place with the same text
      if e notin sink.errors: sink.errors.add e
  let graph = newModuleGraph(cache, conf)
  if not prog.loadConfigsAndProcessCmdLine(cache, conf, graph):
    # In suggest mode the call returns false only after reporting an error through the hook.
    return
  # A .nims file is checked as NimScript, as `nim check foo.nims` does (loadConfigsAndProcessCmdLine
  # sets optWasNimscript); its system module is compiled for the VM and breaks with ORC's defines.
  if conf.selectedGC == gcUnselected and optWasNimscript notin conf.globalOptions:
    initOrcDefines(conf)
  setPipeLinePass(graph, SemPass)
  conf.setCmd cmdCheck
  defineSymbol(conf.symbols, $conf.backend)
  conf.searchPaths.add conf.libpath
  compilePipelineProject(graph)
  if sink.errors.len > 0: return
  let module = graph.getModule(conf.projectMainIdx)
  if module.isNil:
    sink.errors.add CompileError(file: path, message: "the compiler did not produce a module")
    return
  # semtabAll: every top-level symbol of the module, private ones too (allSyms gives only the
  # exported ones, and a private type with =destroy needs a =copy as much as a public one).
  for s in semtabAll(graph, module).data:
    if s.isNil: continue
    # itemId.module: declared in this module, not re-exported from an import. fileIndex: written in
    # this file, not in a file it includes; a finding carries only a line and a column, which would
    # point into the wrong file (the syntax rules do not read included files either).
    if s.itemId.module != module.position or s.info.fileIndex != conf.projectMainIdx or s.typ.isNil:
      continue
    if s.kind in Routines and s.ast != nil and s.ast.len > bodyPos:
      danglingCstrings(s, s.ast[bodyPos], result)
    if s.kind in Routines + {skType}:
      let v = namingVerdict(s, cache)
      if v != nvKeep: naming.add (int(s.info.line), int(s.info.col) + 1, v)
    if s.kind == skType:
      if destroysWithoutCopy(graph, s.typ):
        result.add initFinding(bn11DestroyWithoutCopy, int(s.info.line), int(s.info.col) + 1)
      continue
    if s.kind notin Routines or sfExported notin s.flags or s.typ.n.isNil:
      continue
    let params = s.typ.n
    for i in 1 ..< params.len:
      if params[i].kind != nkSym: continue
      let p = params[i].sym
      if p.typ != nil and p.typ.skipTypes(Transparent).kind == tyBool:
        result.add initFinding(bn02PublicBoolParam, int(p.info.line), int(p.info.col) + 1)

proc analyzeTyped*(path: string; stdlib = builtWithStdlib): TypedAnalysis {.raises: [].} =
  ## Checks the file at `path` with every rule; BN-02 on resolved types (BN-T1, BN-T2). The file is
  ## read here, not passed in, because the compiler reads it from disk too: both see the same file.
  ## A file that cannot be read, does not parse or does not compile gives its errors and no
  ## findings. `stdlib` must
  ## be the `lib` directory of the same Nim version as `builtWithStdlib` (for example after the
  ## installation moved); when it holds no `system.nim` nothing is checked (BN-T5).
  let source =
    try: readFile(path)
    except IOError as e:
      return TypedAnalysis(ok: false, readError: e.msg)
  let syntactic = analyze(source)
  if not syntactic.ok:
    result = TypedAnalysis(ok: false)
    for e in syntactic.parseErrors:
      result.errors.add CompileError(file: path, line: e.line, col: e.col, message: e.message)
    return
  if not fileExists(stdlib / "system.nim"):
    return TypedAnalysis(ok: false, errors: @[CompileError(file: path, message:
      "the Nim standard library this checker was built with is not at " & stdlib &
      "; rebuild beautifulnim with the Nim that should check the code")])
  let sink = ErrorSink()
  var typedBools: seq[Finding]
  var naming: seq[(int, int, NamingVerdict)]
  try:
    typedBools = semCheck(path, stdlib, sink, naming)
  except Exception as e:
    # The compiler's modules carry no raises annotations; whatever escapes is reported, not dropped.
    sink.errors.add CompileError(file: path, message: "the compiler failed: " & e.msg)
  if sink.errors.len > 0:
    return TypedAnalysis(ok: false, errors: sink.errors)
  result = TypedAnalysis(ok: true, findings: typedBools)
  for f in syntactic.findings:
    if f.rule == bn02PublicBoolParam: continue
    var f = f
    if f.rule == bn05Naming:
      if (f.line, f.col, nvDrop) in naming: continue
      if (f.line, f.col, nvWarn) in naming: f.level = lvWarning
    result.findings.add f
  result.findings.sort(proc (a, b: Finding): int =
    result = cmp(a.line, b.line)
    if result == 0: result = cmp(a.col, b.col))
